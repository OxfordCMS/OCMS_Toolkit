def parse_ena_script(infile):
    '''
    parses the download script generated by ENA to identify
    SRR accessions to be downloaded. Returns a dictionary of
    sentinel file (key) and wget download command, fastq file, and
    srr accession (list of values)

    Blank lines and comment lines (such as a ``#!/bin/bash`` line) are
    ignored. A ``ValueError`` is raised if a line does not end in a file URL,
    if two lines download files with the same name, or if the script contains
    no download commands.
    '''

    srr_dict = {}
    with open(infile, 'r') as ena_script:
        for lineno, line in enumerate(ena_script, start=1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            path = line.split("/")
            if len(path) < 3 or not path[-1]:
                raise ValueError(
                    f"{infile}, line {lineno}: expected a download command"
                    f" ending in a file URL, found: {line}")
            # accession subdir is the second last item
            srr = path[-2]
            fq = path[-1]
            sentinel = f".sentinel.{fq}"
            if sentinel in srr_dict:
                raise ValueError(
                    f"{infile}, line {lineno}: {fq} is downloaded more than"
                    " once")
            srr_dict[sentinel] = [line, fq, srr]

    if not srr_dict:
        raise ValueError(f"no download commands found in {infile}")

    return srr_dict


def downloads(infile):
    '''
    Returns a dictionary of downloaded file name (key) and the download
    command (value) from an ENA download script.
    '''
    return {fq: command
            for command, fq, _srr in parse_ena_script(infile).values()}
